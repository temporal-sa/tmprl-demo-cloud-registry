#!/usr/bin/env python3
"""Generate structural Go types from the canonical DemoProject schema.

Semantic validation/defaulting stays handwritten. Run from any directory;
--check verifies generated sources and the embedded schema without writing.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "schemas/project.schema.json"
TARGET = ROOT / "operator-v2/internal/project"
NAMES = {"dnsLabel": "DNSLabel", "envName": "EnvName", "httpsUrl": "HTTPSURL", "goDuration": "GoDuration", "worker": "Worker", "awsIamRoleArn": "AWSIAMRoleARN", "url": "URL", "buildId": "BuildID", "memoryMb": "MemoryMB", "temporalSdks": "TemporalSDKs", "aiSdks": "AISDKs", "caCert": "CACert"}


def name(value: str) -> str:
    return NAMES.get(value, value[0].upper() + value[1:])


def generate(schema: dict) -> bytes:
    # Source is inline in the canonical schema; name it once for typed consumers.
    schema["$defs"]["source"] = schema["properties"]["spec"]["properties"]["source"]
    schema["properties"]["spec"]["properties"]["source"] = {"$ref": "#/$defs/source"}
    definitions = dict(schema["$defs"])
    definitions["spec"] = schema["properties"]["spec"]
    pending: list[tuple[str, dict]] = list(definitions.items())
    written: set[str] = set()
    output = ["// Code generated by tools/generate_project_types.py; DO NOT EDIT.", "package project", 'import "encoding/json"', ""]

    def go_type(value: dict, hint: str, optional: bool = False) -> str:
        if "$ref" in value:
            result = name(value["$ref"].rsplit("/", 1)[-1])
            target = schema["$defs"][value["$ref"].rsplit("/", 1)[-1]]
            composite = target.get("type") in ("array",) or target.get("type") == "object" and not target.get("properties")
        elif "oneOf" in value or "anyOf" in value:
            choices = value.get("oneOf", value.get("anyOf", []))
            types = {choice.get("type") for choice in choices}
            if types <= {"integer", "string"}:
                result, composite = "PortReference", False
            else:
                raise ValueError("Unsupported union: " + hint)
        elif value.get("type") == "object":
            if "properties" in value:
                result, composite = name(hint), False
                pending.append((hint, value))
            elif isinstance(value.get("additionalProperties"), dict):
                result = "map[string]" + go_type(value["additionalProperties"], hint + "Value")
                composite = True
            else:
                # Deliberate extension points, such as canary gate input, stay
                # opaque rather than losing unknown application-owned fields.
                # A pointer preserves absent versus explicitly empty gate
                # input: no workflow argument is distinct from one {} value.
                result, composite = "map[string]json.RawMessage", False
        elif value.get("type") == "array":
            result = "[]" + go_type(value["items"], hint + "Item")
            composite = True
        else:
            kind = value.get("type")
            if kind is None and "const" in value:
                kind = "boolean" if isinstance(value["const"], bool) else "string"
            result = {"string": "string", "integer": "int", "number": "float64", "boolean": "bool"}.get(kind)
            if result is None:
                raise ValueError("Unsupported schema type: " + hint)
            composite = False
        return "*" + result if optional and not composite else result

    index = 0
    while index < len(pending):
        key, definition = pending[index]
        index += 1
        if key in written or key == "worker":
            continue
        written.add(key)
        typename = name(key)
        if definition.get("type") == "object" and "properties" in definition:
            output.append(f"type {typename} struct {{")
            required = definition.get("required", [])
            for field, value in definition["properties"].items():
                fieldtype = go_type(value, typename + name(field), field not in required)
                tag = field if field in required else field + ",omitempty"
                output.append(f'\t{name(field)} {fieldtype} `json:"{tag}"`')
            output.extend(["}", ""])
        else:
            output.extend([f"type {typename} {go_type(definition, typename + 'Value')}", ""])
    return subprocess.check_output(["gofmt"], input="\n".join(output).encode())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = SCHEMA.read_bytes()
    outputs = {TARGET / "types_generated.go": generate(json.loads(data)), TARGET / "schemas/project.schema.json": data}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                print(f"Generated contract differs: {path.relative_to(ROOT)}", file=sys.stderr)
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
